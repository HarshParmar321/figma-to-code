"""Clean export: the downloaded code, without the instruments the design check needs.

The preview keeps `data-figma-id` (and friends) so every element can be measured and corrected.
The download should not: those attributes are noise to a developer, and corrections living in a
separate file keyed by layer ids are not maintainable. Here the corrections are folded into the real
classes (or, when only some elements of a class need one, into a small modifier class), and every
`data-*` attribute the generator added is removed.
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

INTERNAL_ATTRS = ("data-figma-id", "data-section", "data-layout", "data-fit", "data-component")
_ATTR_RE = re.compile(r"\s(?:" + "|".join(INTERNAL_ATTRS) + r')="[^"]*"')
_TAG_RE = re.compile(r"<([a-z][a-z0-9]*)\b([^<>]*?)(/?)>", re.I)
_RULE_RE = re.compile(r'\[data-figma-id="([^"]+)"\]\s*\{([^}]*)\}')
_CORR_MEDIA = re.compile(r"@media\s*\(([^)]*)\)\s*\{(.*?)\n\}", re.S)

README = """\
{name}: generated by Figma to Code

  index.html{pages}      pages
  css/styles.css         all styles (tokens, base, layout, components, sections, responsive)
  components/            sections shared by several pages (header, footer...), ready to include
  images/  fonts/        assets

No build step: open index.html in a browser, or upload the folder to any static host.
Classes follow block__element naming (hero__title); buttons share .btn; tokens are CSS variables
in :root at the top of styles.css. Desktop fine-tuning measured against the Figma design is at the
end of styles.css.
"""


def parse_corrections(css: str) -> list[tuple[str, dict[str, str]]]:
    """[(media condition, {figma id: declarations})] from css/corrections.css (desktop, phone)."""
    return [
        (m.group(1).strip(), {fid: body.strip() for fid, body in _RULE_RE.findall(m.group(2))})
        for m in _CORR_MEDIA.finditer(css)
    ]


def _classes_by_id(htmls: dict[str, str]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for text in htmls.values():
        for tag in _TAG_RE.finditer(text):
            attrs = tag.group(2)
            fid = re.search(r'data-figma-id="([^"]+)"', attrs)
            cls = re.search(r'\sclass="([^"]*)"', attrs)
            if fid and cls:
                out.setdefault(fid.group(1), cls.group(1).split())
    return out


def fold_corrections(htmls: dict[str, str], corrections_css: str) -> tuple[dict[str, str], str]:
    """Returns (htmls with modifier classes added where needed, CSS blocks with the corrections)."""
    blocks = []
    for media, fixes in parse_corrections(corrections_css):
        if fixes:
            htmls, block = _fold(htmls, media, fixes, "phone" if "max-width" in media else "desktop")
            blocks.append(block)
    return htmls, "".join(blocks)


def _fold(htmls: dict[str, str], media: str, fixes: dict[str, str], label: str) -> tuple[dict[str, str], str]:
    classes = _classes_by_id(htmls)
    by_class: dict[str, list[str]] = defaultdict(list)  # first class -> figma ids using it
    for fid, cls in classes.items():
        if cls:
            by_class[cls[0]].append(fid)
    rules: dict[str, str] = {}
    extra: dict[str, str] = {}  # figma id -> modifier class to add
    counter: dict[str, int] = defaultdict(int)
    for fid, decls in fixes.items():
        cls = classes.get(fid)
        if not cls:
            continue
        base = cls[0]
        users = by_class[base]
        if all(fixes.get(other) == decls for other in users):
            rules[f".{base}"] = decls  # every element of this class needs the same nudge
        else:
            counter[base] += 1
            mod = f"{base}--tuned-{counter[base]}" if label == "desktop" else f"{base}--phone-{counter[base]}"
            extra[fid] = mod
            rules[f".{mod}"] = decls
    if extra:

        def add_class(m: re.Match) -> str:
            attrs = m.group(2)
            fid = re.search(r'data-figma-id="([^"]+)"', attrs)
            if fid and fid.group(1) in extra:
                mod = extra[fid.group(1)]
                attrs = re.sub(r'\sclass="([^"]*)"', lambda c: f' class="{c.group(1)} {mod}"', attrs, count=1)
            return f"<{m.group(1)}{attrs}{m.group(3)}>"

        htmls = {k: _TAG_RE.sub(add_class, v) for k, v in htmls.items()}
    body = "\n".join(f"  {sel} {{ {decls} }}" for sel, decls in sorted(rules.items()))
    block = (
        f"\n/* {label.capitalize()} fine-tuning: measured against the Figma {label} design. */\n"
        f"@media ({media or 'min-width: 1024px'}) {{\n{body}\n}}\n"
    )
    return htmls, block


def strip_internal(html: str) -> str:
    html = _ATTR_RE.sub("", html)
    html = html.replace('  <link rel="stylesheet" href="css/corrections.css">\n', "")
    html = re.sub(r'\s(class)=""', "", html)
    return html


def clean_site(out_dir: Path, site_name: str = "Site") -> dict[str, bytes]:
    """All files of the downloadable site: {relative path: bytes}."""
    files: dict[str, bytes] = {}
    htmls: dict[str, str] = {}
    for f in sorted(out_dir.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(out_dir).as_posix()
        if rel == "css/corrections.css":
            continue
        if f.suffix == ".html":
            htmls[rel] = f.read_text(encoding="utf-8")
        else:
            files[rel] = f.read_bytes()
    corr = out_dir / "css" / "corrections.css"
    htmls, block = fold_corrections(htmls, corr.read_text(encoding="utf-8") if corr.exists() else "")
    if block and "css/styles.css" in files:
        files["css/styles.css"] = files["css/styles.css"] + block.encode("utf-8")
    for rel, text in htmls.items():
        files[rel] = strip_internal(text).encode("utf-8")
    pages = sorted(p for p in htmls if "/" not in p and p != "index.html")
    files["README.txt"] = README.format(name=site_name, pages=(", " + ", ".join(pages)) if pages else "").encode(
        "utf-8"
    )
    return files
